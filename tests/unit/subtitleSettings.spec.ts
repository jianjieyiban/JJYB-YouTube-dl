import { describe, expect, it } from 'vitest';
import {
  areSubtitleSettingsEqual,
  buildSubtitleOverride,
  createSubtitleSettings,
  mergeSubtitleSettings,
} from '../../src/helpers/subtitles/settings.ts';
import { defaultSubtitleSettings } from '../../src/tauri/types/config.ts';

describe('subtitle settings helpers', () => {
  it('defaults to Chinese priority and standalone SRT', () => {
    expect(defaultSubtitleSettings).toMatchObject({ chinesePriority: true, embedSubtitles: false });
    expect(defaultSubtitleSettings.formatPreference[0]).toBe('srt');
  });

  it('enables Chinese priority without explicit languages and keeps old values', () => {
    const legacy = { ...defaultSubtitleSettings, languages: [], embedSubtitles: true };
    delete (legacy as Partial<typeof legacy>).chinesePriority;
    expect(createSubtitleSettings(legacy)).toMatchObject({ enabled: true, chinesePriority: true, embedSubtitles: true });
  });

  it('lets explicit task languages override Chinese priority', () => {
    expect(mergeSubtitleSettings(defaultSubtitleSettings, { languages: ['ja'] }))
      .toMatchObject({ chinesePriority: false, languages: ['ja'] });
  });

  it('normalizes subtitle settings consistently', () => {
    expect(createSubtitleSettings({
      ...defaultSubtitleSettings,
      languages: [' EN ', 'en'],
      formatPreference: ['VTT'],
    })).toEqual({
      ...defaultSubtitleSettings,
      enabled: true,
      includeAutoGenerated: false,
      languages: ['en'],
      formatPreference: ['vtt', 'srt', 'ass', 'ttml', 'json3'],
    });
  });

  it('merges overrides on top of global subtitle settings', () => {
    expect(mergeSubtitleSettings(defaultSubtitleSettings, {
      languages: ['de'],
    })).toEqual({
      ...defaultSubtitleSettings,
      enabled: true,
      chinesePriority: false,
      includeAutoGenerated: false,
      languages: ['de'],
    });
  });

  it('compares normalized subtitle settings', () => {
    expect(areSubtitleSettingsEqual(defaultSubtitleSettings, {
      ...defaultSubtitleSettings,
      languages: [],
    })).toBe(true);
  });

  it('builds only changed subtitle override fields', () => {
    expect(buildSubtitleOverride({
      ...defaultSubtitleSettings,
      languages: ['de'],
    }, defaultSubtitleSettings)).toEqual({
      languages: ['de'],
    });
  });

  it('treats an empty language selection as disabled subtitles', () => {
    expect(createSubtitleSettings({
      ...defaultSubtitleSettings,
      chinesePriority: false,
      enabled: true,
      includeAutoGenerated: true,
      languages: [],
    })).toEqual({
      ...defaultSubtitleSettings,
      chinesePriority: false,
      enabled: false,
      includeAutoGenerated: true,
      languages: [],
    });
  });
});
